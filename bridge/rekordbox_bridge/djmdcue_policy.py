"""Explicit support policy for the pyrekordbox ``DjmdCue`` model.

DropDex replaces a track's cue set as a guarded unit, so every column exposed by
our supported pyrekordbox model must have an owner.  Opaque timing/seek fields
are preserved only for the same local cue at unchanged timing; otherwise a
non-default value blocks apply rather than being silently discarded.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Mapping, Optional, Sequence


EDITABLE_SEMANTIC = "editable-semantic"
PRESERVED_SEMANTIC = "preserved-semantic"
WRITER_DERIVED = "writer-derived-regenerated"
UNSUPPORTED_IRRELEVANT = "unsupported-irrelevant"
UNSUPPORTED_BLOCKING = "unsupported-blocking"
_HOT_KIND_BY_SLOT = {1: 1, 2: 2, 3: 3, 4: 5, 5: 6, 6: 7, 7: 8, 8: 9}


@dataclass(frozen=True)
class DjmdCueFieldPolicy:
    classification: str
    rationale: str


